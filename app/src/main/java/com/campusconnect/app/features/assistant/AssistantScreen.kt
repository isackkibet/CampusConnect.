import com.campusconnect.app.ui.components.CampusTopBar
import com.campusconnect.app.ui.components.DemoModeBanner

@Composable
fun AssistantScreen(
    onBack: () -> Unit,
    viewModel: AssistantViewModel = hiltViewModel(),
) {
    val state by viewModel.state.collectAsStateWithLifecycle()
    var text by remember { mutableStateOf("") }
    val listState = rememberLazyListState()

    LaunchedEffect(state.messages.size, state.sending) {
        if (state.messages.isNotEmpty()) listState.animateScrollToItem(state.messages.lastIndex)
    }

    Column(
        modifier = Modifier
            .fillMaxSize()
            .imePadding(),
    ) {
        CampusTopBar(
            title = "Campus assistant",
            subtitle = if (viewModel.remoteConfigured) "Connected to secure AI backend" else "Offline guide mode",
            onBack = onBack,
            actions = {
                IconButton(onClick = { viewModel.reset() }) {
                    Icon(Icons.Filled.Refresh, contentDescription = "Start over")
                }
            },
        )
        Box(modifier = Modifier.padding(horizontal = 16.dp)) {
            DemoModeBanner(
                if (viewModel.remoteConfigured) {
                    "AI answers are generated by the configured backend. Always verify official campus information."
                } else {
                    "Offline guide: answers come from built-in help text, not an AI service or official campus records."
                },
            )
        }
        Spacer(Modifier.height(6.dp))
        LazyRow(
            contentPadding = PaddingValues(horizontal = 16.dp),
            horizontalArrangement = Arrangement.spacedBy(8.dp),
        ) {
            val suggestions = listOf(
                "How do I apply for an attachment?",
                "How do I sell an item safely?",
                "Where can I find accommodation?",
                "How do I RSVP for an event?",
            )
            items(suggestions) { suggestion ->
                AssistChip(
                    onClick = {
                        text = suggestion
                        viewModel.ask(suggestion)
                        text = ""
                    },
                    label = { Text(suggestion) },
                )
            }
        }
        LazyColumn(
            state = listState,
            modifier = Modifier.weight(1f),
            contentPadding = PaddingValues(16.dp),
            verticalArrangement = Arrangement.spacedBy(10.dp),
        ) {
            items(state.messages, key = { it.id }) { message ->
                Column(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalAlignment = if (message.fromUser) Alignment.End else Alignment.Start,
                ) {
                    Surface(
                        shape = RoundedCornerShape(
                            topStart = 16.dp,
                            topEnd = 16.dp,
                            bottomStart = if (message.fromUser) 16.dp else 4.dp,
                            bottomEnd = if (message.fromUser) 4.dp else 16.dp,
                        ),
                        color = if (message.fromUser) MaterialTheme.colorScheme.primary else MaterialTheme.colorScheme.surfaceVariant,
                        modifier = Modifier.fillMaxWidth(0.92f),
                    ) {
                        Column(modifier = Modifier.padding(12.dp)) {
                            if (!message.fromUser) {
                                Row(verticalAlignment = Alignment.CenterVertically) {
                                    Icon(
                                        Icons.Filled.AutoAwesome,
                                        contentDescription = null,
                                        modifier = Modifier.size(14.dp),
                                        tint = MaterialTheme.colorScheme.primary,
                                    )
                                    Spacer(Modifier.width(4.dp))
                                    Text(
                                        "CampusConnect guide",
                                        style = MaterialTheme.typography.labelSmall,
                                        color = MaterialTheme.colorScheme.primary,
                                    )
                                }
                                Spacer(Modifier.height(4.dp))
                            }
                            Text(
                                message.content,
                                style = MaterialTheme.typography.bodyMedium,
                                color = if (message.fromUser) MaterialTheme.colorScheme.onPrimary
                                else MaterialTheme.colorScheme.onSurface,
                            )
                        }
                    }
                }
            }
            if (state.sending) {
                item {
                    Row(verticalAlignment = Alignment.CenterVertically) {
                        CircularProgressIndicator(modifier = Modifier.size(16.dp), strokeWidth = 2.dp)
                        Spacer(Modifier.width(8.dp))
                        Text("Thinking…", style = MaterialTheme.typography.labelSmall)
                    }
                }
            }
        }
        state.lastSource?.let { source ->
            Text(
                if (source == AssistantSource.REMOTE) "Last answer: secure backend" else "Last answer: offline guide",
                style = MaterialTheme.typography.labelSmall,
                color = MaterialTheme.colorScheme.onSurfaceVariant,
                modifier = Modifier.padding(horizontal = 18.dp),
            )
        }
        Row(
            modifier = Modifier
                .fillMaxWidth()
                .padding(8.dp),
            verticalAlignment = Alignment.CenterVertically,
        ) {
            OutlinedTextField(
                value = text,
                onValueChange = { text = it.take(500) },
                placeholder = { Text("Ask about the app…") },
                modifier = Modifier.weight(1f),
                maxLines = 3,
                shape = RoundedCornerShape(16.dp),
            )
            IconButton(
                onClick = {
                    if (text.isNotBlank()) {
                        viewModel.ask(text)
                        text = ""
                    }
                },
            ) {
                Icon(Icons.AutoMirrored.Filled.Send, contentDescription = "Send question")
            }
        }
    }
}
